"""Accuracy benchmark: every labelled configuration through the real scan pipeline, no AI.

    python scripts/benchmark.py            # print the results
    python scripts/benchmark.py --write    # also regenerate benchmark/RESULTS.md

Ground truth is ``benchmark/labels.json`` (see its _README). For a label ``fail`` the check is:
  detected    a decided FAIL
  provisional a FAIL the engine only suspects (heuristic, or an AI proposal awaiting confirmation)
  undecided   UNKNOWN / NOT_CONFIGURED
  missed      a PASS or N/A: the engine said it was fine
For a label ``pass``: correct (a decided PASS), false alarm (any FAIL), undecided otherwise.
The knowledge used is what ships: an empty database loaded with the seed recognizers only.
"""

from __future__ import annotations

import json
import sys
import time
from collections import Counter
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
ROOT = BACKEND.parent
sys.path.insert(0, str(BACKEND))

LABELS = ROOT / "benchmark" / "labels.json"
RESULTS = ROOT / "benchmark" / "RESULTS.md"
DECISIVE = {"parser", "confirmed", "default"}


def _isolated_engine():
    from app.cli import isolated_engine

    isolated_engine()


def _scan(path: Path) -> tuple[dict[str, list[dict]], float, str]:
    from app.api.routes.scan import run_scan

    start = time.perf_counter()
    scan = run_scan([(path.name, path.read_text(encoding="utf-8"))]).model_dump()
    elapsed = time.perf_counter() - start
    by_control: dict[str, list[dict]] = {}
    for r in scan["results"]:
        by_control.setdefault(r["control_id"], []).append(r)
    return by_control, elapsed, scan["devices"][0].get("vendor", "unknown")


def _judge(results: list[dict], want: str) -> str:
    statuses = {r["status"] for r in results}
    decided_fail = any(r["status"] == "fail" and r.get("assurance") in DECISIVE for r in results)
    suspected = any(r["status"] == "fail" or r.get("proposed_status") == "fail" for r in results)
    if want == "fail":
        if decided_fail:
            return "detected"
        if suspected:
            return "provisional"
        return "missed" if statuses & {"pass", "n_a"} else "undecided"
    if any(r["status"] == "fail" for r in results):
        return "false_alarm"
    decided_pass = statuses == {"pass"} and all(r.get("assurance") in DECISIVE for r in results)
    return "correct" if decided_pass else "undecided"


def run(isolate: bool = True) -> dict:
    """``isolate`` False: the caller (a test) already provides an isolated, seeded database and no AI."""
    if isolate:
        _isolated_engine()
    labels = json.loads(LABELS.read_text(encoding="utf-8"))
    report = {}
    for group in ("planted", "fixtures"):
        rows = []
        for name, label in labels[group].items():
            by_control, elapsed, vendor = _scan(ROOT / name)
            outcomes = {cid: _judge(by_control.get(cid, []), want)
                        for want in ("fail", "pass") for cid in label[want]}
            rows.append({"file": name, "vendor": vendor, "seconds": round(elapsed, 3),
                         "fail": {cid: outcomes[cid] for cid in label["fail"]},
                         "pass": {cid: outcomes[cid] for cid in label["pass"]}})
        report[group] = rows
    return report


def totals(rows: list[dict]) -> tuple[Counter, Counter]:
    fails, passes = Counter(), Counter()
    for row in rows:
        fails.update(row["fail"].values())
        passes.update(row["pass"].values())
    return fails, passes


def _line(fails: Counter, passes: Counter) -> str:
    planted, secure = sum(fails.values()), sum(passes.values())
    return (f"**{fails['detected']}/{planted}** insecure settings detected as a decided FAIL "
            f"({fails['provisional']} more flagged as suspected, {fails['undecided']} left undecided, "
            f"**{fails['missed']} missed**) · **{passes['false_alarm']} false alarms** on {secure} secure settings "
            f"({passes['correct']} confirmed secure, {passes['undecided']} undecided)")


def markdown(report: dict) -> str:
    out = ["# Benchmark results", "",
           "Generated by `backend/scripts/benchmark.py --write` from `benchmark/labels.json`. Do not edit by hand.",
           "Shipped knowledge only, no AI. A miss means the engine called an insecure setting fine; a false alarm "
           "means it failed a secure one.", ""]
    for group, title in (("planted", "Planted vulnerabilities (labelled with the demo files, before any scan)"),
                         ("fixtures", "Labelled fixtures: 8 vendors, Terraform for AWS, Azure, GCP, and Azure NSG / GCP firewall exports (labels written by reading each file)")):
        fails, passes = totals(report[group])
        out += [f"## {title}", "", _line(fails, passes), "",
                "| File | Vendor path | Detected | Suspected | Undecided | Missed | False alarms | Time |",
                "|---|---|---|---|---|---|---|---|"]
        for row in report[group]:
            f, p = Counter(row["fail"].values()), Counter(row["pass"].values())
            out.append(f"| `{row['file']}` | {row['vendor']} | {f['detected']}/{len(row['fail'])} | "
                       f"{f['provisional']} | {f['undecided']} | {f['missed']} | {p['false_alarm']} | "
                       f"{row['seconds'] * 1000:.0f} ms |")
        not_detected = [(row["file"], cid, o) for row in report[group] for cid, o in row["fail"].items()
                        if o != "detected"]
        alarms = [(row["file"], cid) for row in report[group] for cid, o in row["pass"].items() if o == "false_alarm"]
        if not_detected:
            out += ["", "Not detected as a decided FAIL:", ""]
            out += [f"- `{Path(f).name}` {cid}: {o}" for f, cid, o in not_detected]
        if alarms:
            out += ["", "False alarms:", ""]
            out += [f"- `{Path(f).name}` {cid}" for f, cid in alarms]
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    import logging
    logging.disable(logging.WARNING)
    result = run()
    for group in ("planted", "fixtures"):
        print(group, _line(*totals(result[group])))
    if "--write" in sys.argv:
        RESULTS.write_text(markdown(result), encoding="utf-8")
        print(f"wrote {RESULTS.relative_to(ROOT)}")
